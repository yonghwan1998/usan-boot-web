package com.usanmap.usan.repository;

import com.usanmap.usan.entity.ListingSendBatch;
import org.hibernate.cfg.Configuration;
import org.junit.jupiter.api.Test;

import java.sql.DriverManager;
import java.util.UUID;

class ListingSendBatchSchemaTests {
    @Test
    void validatesExplicitDeploymentColumnNames() throws Exception {
        String url = "jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1";
        try (var connection = DriverManager.getConnection(url);
             var statement = connection.createStatement()) {
            // Entity에서 생성하지 않은 배포용 DB 스키마로 컬럼명 계약을 확인한다.
            statement.execute("""
                    CREATE TABLE listing_send_batch (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        listing_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
                        listing_title VARCHAR(255) NOT NULL, listing_address VARCHAR(512) NOT NULL,
                        listing_created_at TIMESTAMP, listing_updated_at TIMESTAMP,
                        message_type VARCHAR(10) NOT NULL, recipient_count INT NOT NULL,
                        request_status VARCHAR(20) NOT NULL, provider_request_id VARCHAR(100),
                        credit_ledger_id BIGINT, credit_before INT, credit_used INT, credit_after INT,
                        requested_at TIMESTAMP NOT NULL, accepted_at TIMESTAMP,
                        selection_radius_m INT, selection_listing_types VARCHAR(500),
                        updated_at TIMESTAMP NOT NULL
                    )
                    """);
            Configuration configuration = new Configuration().addAnnotatedClass(ListingSendBatch.class)
                    .setProperty("hibernate.connection.driver_class", "org.h2.Driver")
                    .setProperty("hibernate.connection.url", url)
                    .setProperty("hibernate.hbm2ddl.auto", "validate")
                    .setProperty("hibernate.physical_naming_strategy",
                            "org.hibernate.boot.model.naming.CamelCaseToUnderscoresNamingStrategy");
            try (var factory = configuration.buildSessionFactory()) {
                org.assertj.core.api.Assertions.assertThat(factory.isOpen()).isTrue();
            }
        }
    }
}
